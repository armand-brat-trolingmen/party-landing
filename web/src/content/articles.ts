export function getArticlePath(article: Pick<ArticleEntity, 'slug'>) {
  return `/articles/${article.slug}`;
}

export function getAllArticleUrls() {
  return articles.map((article) => getArticlePath(article)).sort();
}

export function findArticleBySlug(slug: string) {
  return articles.find((article) => article.slug === slug);
}

function getBlockText(block: ArticleTextBlock) {
  if (block.kind === 'paragraph') {
    return block.text;
  }

  return block.items.join(' ');
}

export function getArticleTextContent(article: ArticleEntity) {
  const sectionText = article.sections
    .flatMap((section) => [section.title, ...section.blocks.map(getBlockText)])
    .join(' ');
  const faqText = article.faq.map((item) => `${item.question} ${item.answer}`).join(' ');

  return [article.h1, article.description, article.lead, sectionText, faqText].join(' ');
}
